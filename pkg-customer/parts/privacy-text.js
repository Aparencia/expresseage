function normalizeVersion(value) {
  const version = typeof value === 'string' ? value.trim() : '';
  return /^[A-Za-z0-9._-]{1,32}$/.test(version) ? version : '当前版本';
}

function fill(text, version) {
  return String(text).split('{version}').join(version).split('{contact}').join(CONTACT_PLACEHOLDER);
}

function buildSections(privacyVersion) {
  const version = normalizeVersion(privacyVersion);
  return SECTIONS.map((section) => ({
    title: fill(section.title, version),
    paragraphs: section.paragraphs.map((paragraph) => fill(paragraph, version))
  }));
}

function buildParagraphs(privacyVersion) {
  const out = [];
  buildSections(privacyVersion).forEach((section) => {
    out.push(section.title);
    section.paragraphs.forEach((paragraph) => out.push(paragraph));
  });
  return out;
}

function buildText(privacyVersion) {
  return buildParagraphs(privacyVersion).join('\n');
}

